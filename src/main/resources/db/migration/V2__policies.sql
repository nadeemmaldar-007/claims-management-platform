-- Policy reference data: a local snapshot that stands in for the policy administration system.

CREATE TABLE policies (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    policy_number VARCHAR(30)   NOT NULL,
    market_id     BIGINT        NOT NULL,
    product_type  VARCHAR(20)   NOT NULL,
    holder_id     BIGINT        NOT NULL,
    insured_item  VARCHAR(200)  NOT NULL,
    sum_insured   NUMERIC(19,2) NOT NULL,
    deductible    NUMERIC(19,2) NOT NULL,
    valid_from    DATE          NOT NULL,
    valid_to      DATE          NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_policies PRIMARY KEY (id),
    CONSTRAINT uq_policies_policy_number UNIQUE (policy_number),
    CONSTRAINT fk_policies_market_id FOREIGN KEY (market_id) REFERENCES markets (id),
    CONSTRAINT fk_policies_holder_id FOREIGN KEY (holder_id) REFERENCES app_users (id),
    CONSTRAINT ck_policies_product_type CHECK (product_type IN ('MOTOR', 'PROPERTY')),
    CONSTRAINT ck_policies_status CHECK (status IN ('ACTIVE', 'LAPSED', 'CANCELLED'))
);
