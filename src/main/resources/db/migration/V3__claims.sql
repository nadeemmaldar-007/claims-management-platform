-- Claims and everything owned by the claim module.

CREATE TABLE claim_counters (
    claim_type VARCHAR(20) NOT NULL,
    next_value BIGINT      NOT NULL,
    CONSTRAINT pk_claim_counters PRIMARY KEY (claim_type),
    CONSTRAINT ck_claim_counters_claim_type CHECK (claim_type IN ('MOTOR', 'PROPERTY'))
);

CREATE TABLE claims (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_number                VARCHAR(20)   NOT NULL,
    claim_type                  VARCHAR(20)   NOT NULL,
    status                      VARCHAR(30)   NOT NULL,
    -- A logical reference only: the claim module does not depend on the policy module, so no foreign key.
    policy_number               VARCHAR(30)   NOT NULL,
    policy_sum_insured          NUMERIC(19,2) NOT NULL,
    policy_deductible           NUMERIC(19,2) NOT NULL,
    claimant_id                 BIGINT        NOT NULL,
    market_id                   BIGINT        NOT NULL,
    assigned_officer_id         BIGINT,
    assigned_at                 TIMESTAMP WITH TIME ZONE,
    currency_code               VARCHAR(3)    NOT NULL,
    claimed_amount              NUMERIC(19,2) NOT NULL,
    incident_date               DATE          NOT NULL,
    incident_location           VARCHAR(200)  NOT NULL,
    description                 VARCHAR(1000) NOT NULL,
    vehicle_registration_number VARCHAR(20),
    vehicle_make                VARCHAR(50),
    vehicle_model               VARCHAR(50),
    vehicle_year                INTEGER,
    damage_type                 VARCHAR(20),
    police_report_number        VARCHAR(50),
    property_address            VARCHAR(300),
    property_type               VARCHAR(20),
    peril_type                  VARCHAR(20),
    decision_type               VARCHAR(20),
    decision_reason             VARCHAR(40),
    decision_remarks            VARCHAR(1000),
    decided_by_id               BIGINT,
    decided_at                  TIMESTAMP WITH TIME ZONE,
    approved_amount             NUMERIC(19,2),
    payment_method              VARCHAR(20),
    payment_reference           VARCHAR(40),
    settled_amount              NUMERIC(19,2),
    settled_at                  TIMESTAMP WITH TIME ZONE,
    version                     BIGINT        NOT NULL DEFAULT 0,
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_claims PRIMARY KEY (id),
    CONSTRAINT uq_claims_claim_number UNIQUE (claim_number),
    CONSTRAINT fk_claims_claimant_id FOREIGN KEY (claimant_id) REFERENCES app_users (id),
    CONSTRAINT fk_claims_market_id FOREIGN KEY (market_id) REFERENCES markets (id),
    CONSTRAINT fk_claims_assigned_officer_id FOREIGN KEY (assigned_officer_id) REFERENCES app_users (id),
    CONSTRAINT fk_claims_decided_by_id FOREIGN KEY (decided_by_id) REFERENCES app_users (id),
    CONSTRAINT ck_claims_claim_type CHECK (claim_type IN ('MOTOR', 'PROPERTY')),
    CONSTRAINT ck_claims_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'PENDING_INFORMATION', 'ESCALATED',
                                                  'APPROVED', 'REJECTED', 'SETTLED')),
    CONSTRAINT ck_claims_damage_type CHECK (damage_type IN ('COLLISION', 'THEFT', 'FIRE', 'FLOOD', 'VANDALISM',
                                                            'OTHER')),
    CONSTRAINT ck_claims_property_type CHECK (property_type IN ('RESIDENTIAL', 'COMMERCIAL', 'INDUSTRIAL')),
    CONSTRAINT ck_claims_peril_type CHECK (peril_type IN ('FIRE', 'FLOOD', 'STORM', 'THEFT', 'VANDALISM', 'OTHER')),
    CONSTRAINT ck_claims_decision_type CHECK (decision_type IN ('APPROVED', 'REJECTED')),
    CONSTRAINT ck_claims_decision_reason CHECK (decision_reason IN ('POLICY_INACTIVE', 'NOT_COVERED',
                                                                    'FRAUD_SUSPECTED', 'INSUFFICIENT_EVIDENCE',
                                                                    'DUPLICATE_CLAIM', 'INFORMATION_NOT_PROVIDED',
                                                                    'OTHER')),
    CONSTRAINT ck_claims_payment_method CHECK (payment_method IN ('BANK_TRANSFER', 'CHEQUE'))
);

CREATE INDEX ix_claims_claimant_id ON claims (claimant_id);
CREATE INDEX ix_claims_market_id_status ON claims (market_id, status);
CREATE INDEX ix_claims_assigned_officer_id_status ON claims (assigned_officer_id, status);
-- Supports the duplicate-claim check at submission.
CREATE INDEX ix_claims_policy_number_incident_date_claim_type ON claims (policy_number, incident_date, claim_type);

CREATE TABLE claim_assessments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_id             BIGINT        NOT NULL,
    assessed_by_id       BIGINT        NOT NULL,
    assessed_loss_amount NUMERIC(19,2) NOT NULL,
    deductible_applied   NUMERIC(19,2) NOT NULL,
    recommended_payout   NUMERIC(19,2) NOT NULL,
    coverage_confirmed   BOOLEAN       NOT NULL,
    recommendation       VARCHAR(20)   NOT NULL,
    notes                VARCHAR(2000),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_claim_assessments PRIMARY KEY (id),
    CONSTRAINT fk_claim_assessments_claim_id FOREIGN KEY (claim_id) REFERENCES claims (id),
    CONSTRAINT fk_claim_assessments_assessed_by_id FOREIGN KEY (assessed_by_id) REFERENCES app_users (id),
    CONSTRAINT ck_claim_assessments_recommendation CHECK (recommendation IN ('APPROVE', 'REJECT', 'ESCALATE'))
);

CREATE TABLE information_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_id        BIGINT        NOT NULL,
    requested_by_id BIGINT        NOT NULL,
    question        VARCHAR(1000) NOT NULL,
    due_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    response_text   VARCHAR(2000),
    responded_by_id BIGINT,
    responded_at    TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_information_requests PRIMARY KEY (id),
    CONSTRAINT fk_information_requests_claim_id FOREIGN KEY (claim_id) REFERENCES claims (id),
    CONSTRAINT fk_information_requests_requested_by_id FOREIGN KEY (requested_by_id) REFERENCES app_users (id),
    CONSTRAINT fk_information_requests_responded_by_id FOREIGN KEY (responded_by_id) REFERENCES app_users (id),
    CONSTRAINT ck_information_requests_status CHECK (status IN ('OPEN', 'RESPONDED', 'CANCELLED'))
);

-- Append-only audit trail. actor_user_id is a value, not a foreign key, so the trail survives account changes.
CREATE TABLE claim_timeline_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_id      BIGINT        NOT NULL,
    entry_type    VARCHAR(40)   NOT NULL,
    from_status   VARCHAR(30),
    to_status     VARCHAR(30),
    actor_user_id VARCHAR(30)   NOT NULL,
    message       VARCHAR(1000) NOT NULL,
    visibility    VARCHAR(20)   NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_claim_timeline_entries PRIMARY KEY (id),
    CONSTRAINT fk_claim_timeline_entries_claim_id FOREIGN KEY (claim_id) REFERENCES claims (id),
    CONSTRAINT ck_claim_timeline_entries_entry_type CHECK (entry_type IN ('SUBMITTED', 'ASSIGNED', 'REASSIGNED',
                                                                          'ASSESSMENT_RECORDED',
                                                                          'INFORMATION_REQUESTED',
                                                                          'INFORMATION_PROVIDED',
                                                                          'INFORMATION_REQUEST_CANCELLED',
                                                                          'ESCALATED', 'APPROVED', 'REJECTED',
                                                                          'SETTLED')),
    CONSTRAINT ck_claim_timeline_entries_from_status CHECK (from_status IN ('SUBMITTED', 'UNDER_REVIEW',
                                                                            'PENDING_INFORMATION', 'ESCALATED',
                                                                            'APPROVED', 'REJECTED', 'SETTLED')),
    CONSTRAINT ck_claim_timeline_entries_to_status CHECK (to_status IN ('SUBMITTED', 'UNDER_REVIEW',
                                                                        'PENDING_INFORMATION', 'ESCALATED',
                                                                        'APPROVED', 'REJECTED', 'SETTLED')),
    CONSTRAINT ck_claim_timeline_entries_visibility CHECK (visibility IN ('PUBLIC', 'INTERNAL'))
);

CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id         BIGINT      NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    claim_number    VARCHAR(20) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_idempotency_keys PRIMARY KEY (id),
    CONSTRAINT fk_idempotency_keys_user_id FOREIGN KEY (user_id) REFERENCES app_users (id),
    CONSTRAINT uq_idempotency_keys_user_id_idempotency_key UNIQUE (user_id, idempotency_key)
);
