-- Markets and identity. Portable SQL: runs unchanged on PostgreSQL 17 and on H2 in PostgreSQL mode.

CREATE TABLE markets (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code                 VARCHAR(2)    NOT NULL,
    country_name         VARCHAR(60)   NOT NULL,
    currency_code        VARCHAR(3)    NOT NULL,
    escalation_threshold NUMERIC(19,2) NOT NULL,
    active               BOOLEAN       NOT NULL,
    CONSTRAINT pk_markets PRIMARY KEY (id),
    CONSTRAINT uq_markets_code UNIQUE (code)
);

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id       VARCHAR(30)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    market_id     BIGINT,
    active        BOOLEAN      NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_app_users PRIMARY KEY (id),
    CONSTRAINT uq_app_users_user_id UNIQUE (user_id),
    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT fk_app_users_market_id FOREIGN KEY (market_id) REFERENCES markets (id),
    CONSTRAINT ck_app_users_role CHECK (role IN ('CLAIMANT', 'OFFICER', 'MANAGER')),
    -- Only managers work across markets; everyone else belongs to exactly one.
    CONSTRAINT ck_app_users_market_required CHECK (role = 'MANAGER' OR market_id IS NOT NULL)
);
