-- In-app notifications, owned by the notification module.

CREATE TABLE notifications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    recipient_id      BIGINT        NOT NULL,
    claim_number      VARCHAR(20)   NOT NULL,
    notification_type VARCHAR(30)   NOT NULL,
    title             VARCHAR(150)  NOT NULL,
    message           VARCHAR(1000) NOT NULL,
    read_flag         BOOLEAN       NOT NULL,
    source_event_id   VARCHAR(36)   NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at           TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_recipient_id FOREIGN KEY (recipient_id) REFERENCES app_users (id),
    -- Makes event handling idempotent: a redelivered event cannot create a second notification.
    CONSTRAINT uq_notifications_source_event_id_recipient_id UNIQUE (source_event_id, recipient_id),
    CONSTRAINT ck_notifications_notification_type CHECK (notification_type IN ('CLAIM_SUBMITTED',
                                                                               'NEW_CLAIM_IN_QUEUE',
                                                                               'CLAIM_ASSIGNED',
                                                                               'INFORMATION_REQUESTED',
                                                                               'INFORMATION_PROVIDED',
                                                                               'CLAIM_ESCALATED',
                                                                               'CLAIM_APPROVED',
                                                                               'CLAIM_REJECTED',
                                                                               'CLAIM_SETTLED'))
);

CREATE INDEX ix_notifications_recipient_id_read_flag ON notifications (recipient_id, read_flag);
