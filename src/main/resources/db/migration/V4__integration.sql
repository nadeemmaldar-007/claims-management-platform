-- Transactional outbox and payment instructions, owned by the integration module.
-- Both refer to claims by value (aggregate_id, claim_number) rather than by foreign key.

CREATE TABLE outbox_events (
    id              VARCHAR(36)   NOT NULL,
    aggregate_type  VARCHAR(30)   NOT NULL,
    aggregate_id    VARCHAR(50)   NOT NULL,
    event_type      VARCHAR(50)   NOT NULL,
    payload         VARCHAR(8000) NOT NULL,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    attempts        INTEGER       NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    processed_at    TIMESTAMP WITH TIME ZONE,
    last_error      VARCHAR(1000),
    CONSTRAINT pk_outbox_events PRIMARY KEY (id),
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'PROCESSED', 'FAILED'))
);

-- The relay looks for PENDING rows whose next_attempt_at has passed.
CREATE INDEX ix_outbox_events_status_next_attempt_at ON outbox_events (status, next_attempt_at);

CREATE TABLE payment_instructions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    claim_number   VARCHAR(20)   NOT NULL,
    amount         NUMERIC(19,2) NOT NULL,
    currency_code  VARCHAR(3)    NOT NULL,
    payment_method VARCHAR(20)   NOT NULL,
    reference      VARCHAR(40)   NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_payment_instructions PRIMARY KEY (id),
    -- One instruction per claim is what makes settlement idempotent.
    CONSTRAINT uq_payment_instructions_claim_number UNIQUE (claim_number),
    CONSTRAINT uq_payment_instructions_reference UNIQUE (reference),
    CONSTRAINT ck_payment_instructions_payment_method CHECK (payment_method IN ('BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_payment_instructions_status CHECK (status IN ('INITIATED', 'COMPLETED', 'FAILED'))
);
